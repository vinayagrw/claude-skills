#!/usr/bin/env node
/**
 * init-finops.mjs — scaffold the runtime FinOps layer into a repo.
 *
 * Three jobs:
 *   1. Copy templates/ into a target repo, idempotently and non-destructively.
 *   2. GENERATE pricing.ts from references/sota-snapshot.md. This is the mechanism that
 *      makes "prices live in exactly one file" true rather than aspirational: pricing.ts
 *      is a build artifact, so a refresh updates one file and regenerates the rest. A
 *      hand-maintained parallel price table is the failure this exists to prevent.
 *   3. Inject the project-context snippet into the repo's agent context file, so the
 *      dev-time rules travel with the codebase instead of living in one session's head.
 *
 * NON-DESTRUCTIVE BY DEFAULT. An existing file is never silently overwritten: the new
 * version lands beside it as `<name>.new` and is reported. Running this twice on a live
 * repo must be safe, because you will run it twice — once to scaffold, once after a
 * price refresh, and by then the templates will have been edited.
 *
 * Node builtins only.
 */

import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { SKILL_ROOT, isSeedable, loadSnapshot, toIso } from './lib/snapshot.mjs';

const TEMPLATES = join(SKILL_ROOT, 'templates');

const HELP = `
init-finops.mjs — scaffold metered LLM plumbing into a repo, and generate pricing.ts

USAGE
  node scripts/init-finops.mjs --target <repo-dir> [options]
  node scripts/init-finops.mjs                          # regenerate this skill's pricing.ts only

OPTIONS
  --target <dir>      Repo to scaffold into. Omit to only regenerate the skill's own
                      templates/pricing.ts from the snapshot (refresh-protocol step 6).
  --dest <subdir>     Where templates land inside the target.  (default: src/finops)
  --context-file <f>  Agent context file to inject the project snippet into.
                      (default: auto — CLAUDE.md if present, else AGENTS.md, else CLAUDE.md)
  --force             Overwrite existing files instead of writing <name>.new beside them.
  --dry-run           Print the plan, change nothing.
  --no-context        Skip the project-context injection.
  --help              This text.

EXIT CODES
  0 done | 1 nothing written because every file already existed (see the .new report)
  4 could not run (unreadable snapshot, missing templates, bad arguments)

AFTER RUNNING
  1. node scripts/check-prices.mjs        — confirm no price leaked out of the snapshot
  2. Read templates/VERIFY.md before trusting costUsd from any UNVERIFIED adapter.
  3. Pick a budget mode deliberately. The default is advisory, which never blocks; that
     is a real choice for a demo and the wrong one for production traffic.
`;

function parseArgs(argv) {
  const o = { target: null, dest: join('src', 'finops'), contextFile: null, force: false, dryRun: false, context: true };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--help' || a === '-h') return { help: true };
    else if (a === '--target') o.target = argv[++i];
    else if (a === '--dest') o.dest = argv[++i];
    else if (a === '--context-file') o.contextFile = argv[++i];
    else if (a === '--force') o.force = true;
    else if (a === '--dry-run') o.dryRun = true;
    else if (a === '--no-context') o.context = false;
    else return { error: `Unknown argument: ${a}` };
  }
  return o;
}

/* ------------------------------------------------------------------ pricing.ts */

const TS_HEADER = (snapshotDate, generatedAt, counts) => `/**
 * pricing.ts — GENERATED FILE. DO NOT HAND-EDIT.
 *
 * Generated by scripts/init-finops.mjs from references/sota-snapshot.md
 *   price sheet revision : ${snapshotDate}
 *   generated            : ${generatedAt}
 *   rows seeded          : ${counts.seeded}   (rows excluded as unverified: ${counts.excluded})
 *
 * To change a price: edit the snapshot, then re-run init-finops.mjs. Editing this file
 * directly creates a second source of truth, and the second source is the one that goes
 * stale silently — it will not be touched by the next refresh.
 *
 * Rates are USD per 1,000,000 tokens. Confidence follows the snapshot's contract:
 *   high   = read off a primary vendor page in a session that fetched it
 *   medium = derived from a verified base, or a primary source that did not state the
 *            relationship explicitly
 * Rows labelled low are QUARANTINED at parse time and never reach this file. If you need
 * one of them, fetch the primary source first and promote the row in the snapshot.
 */
`;

const TS_TYPES = `
export type Confidence = 'high' | 'medium' | 'low';

export interface ContextTier {
  /** Comparison against the prompt token count, e.g. '<=' with 200000. */
  op: '<=' | '<' | '>' | '>=';
  maxPromptTokens: number;
}

export interface PriceEntry {
  modelId: string;
  /** Full label from the snapshot, including any variant or context qualifier. */
  label: string;
  provider: string;
  inputPerMTok: number;
  outputPerMTok: number;
  /** Null where the provider publishes no cached-read rate for this model. */
  cacheReadPerMTok: number | null;
  /** Derived, not stored: see deriveCacheWrites(). Null where the provider has no such rate. */
  cacheWrite5mPerMTok: number | null;
  cacheWrite1hPerMTok: number | null;
  status: string;
  /** Date a human confirmed this row against its primary source. */
  verified: string;
  /** Date this row's pricing takes effect. Null means "as long as anyone has records". */
  effective: string | null;
  /**
   * Date this row STOPS being in force, derived from the next dated row for the same
   * model. This is the effective-date axis: it is why a scheduled step-up prices
   * correctly on both sides of the change date with no code deploy.
   */
  effectiveUntil: string | null;
  contextTier: ContextTier | null;
  source: string;
  confidence: Confidence;
}

export interface PlatformMultiplier {
  platform: string;
  routingTier: string;
  multiplier: number;
  appliesTo: string;
  note: string | null;
  confidence: Confidence;
}

export interface UsageLike {
  inputTokens: number;
  outputTokens: number;
  cacheReadTokens?: number;
  cacheWriteTokens?: number;
  /**
   * Reasoning tokens. Whether these are ALREADY inside outputTokens differs by provider
   * and the default provider is the outlier — Gemini reports them as a sibling addend,
   * everyone else as a nested breakdown. The adapter must set reasoningInOutput
   * accordingly; getting it wrong undercounts output cost by the entire thinking budget.
   */
  reasoningTokens?: number | null;
  reasoningInOutput: boolean;
}

export interface CostOptions {
  /** Asynchronous batch submission. Stacks with cache reads. */
  batch?: boolean;
  /** Prompt size, used to select a context tier where the provider surcharges long prompts. */
  promptTokens?: number;
  /** Partner-cloud or residency routing, e.g. { platform: 'aws-bedrock', routingTier: 'regional' }. */
  routing?: { platform: string; routingTier: string };
  /** Date to price at. Defaults to now. Historical entries reprice correctly. */
  atDate?: string;
}

export interface CostResult {
  costUsd: number;
  entry: PriceEntry | null;
  /** How the model id was resolved. 'default' means the number is a guess — treat as a defect. */
  match: 'exact' | 'alias' | 'default';
  estimated: boolean;
  priceSheetRev: string;
  confidence: Confidence;
  multiplierApplied: number;
}
`;

function tsString(v) {
  if (v === null || v === undefined) return 'null';
  return JSON.stringify(String(v));
}
function tsNum(v) {
  return v === null || v === undefined ? 'null' : String(v);
}

/**
 * Compute effectiveUntil by chaining dated rows for the same model id. Two rows for
 * claude-sonnet-5 (intro, then standard from a named date) become a closed interval and
 * an open one — which is what lets priceFor(model, atDate) be correct across the step-up
 * without anyone remembering to patch the table on the day.
 *
 * Context-tier variants are chained separately: a >200k row is not the successor of a
 * <=200k row, it is a sibling. Conflating them would price long prompts at the short rate.
 */
function chainEffectiveDates(rows) {
  const groups = new Map();
  for (const r of rows) {
    const key = `${r.provider}::${r.id}::${r.contextTier ? r.contextTier.op + r.contextTier.maxPromptTokens : ''}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(r);
  }
  for (const list of groups.values()) {
    const dated = list.filter((r) => r.effective).sort((a, b) => a.effective.localeCompare(b.effective));
    for (let i = 0; i < dated.length; i++) dated[i].effectiveUntil = dated[i + 1] ? dated[i + 1].effective : null;
    for (const r of list) if (!('effectiveUntil' in r)) r.effectiveUntil = null;
  }
  return rows;
}

/**
 * Anthropic publishes cache writes as fixed multiples of the input rate rather than as
 * independent numbers. Deriving them means the refresh only has to touch one column, and
 * a typo in a derived value is impossible. Other providers differ, so we do not guess:
 * an absent rate is null, and null is not zero.
 */
function deriveCacheWrites(row) {
  if (row.provider === 'anthropic' && row.inputPerMTok !== null) {
    return { w5: round(row.inputPerMTok * 1.25), w1h: round(row.inputPerMTok * 2) };
  }
  if (row.provider === 'openai' && row.inputPerMTok !== null) {
    return { w5: round(row.inputPerMTok * 1.25), w1h: null };
  }
  return { w5: null, w1h: null };
}
const round = (n) => Math.round(n * 1e6) / 1e6;

function generatePricingTs(snapshot) {
  const seedable = snapshot.prices.filter(isSeedable);
  const excluded = snapshot.prices.length - seedable.length;
  chainEffectiveDates(seedable);

  const entries = seedable.map((r) => {
    const { w5, w1h } = deriveCacheWrites(r);
    return `  {
    modelId: ${tsString(r.id)},
    label: ${tsString(r.label)},
    provider: ${tsString(r.provider)},
    inputPerMTok: ${tsNum(r.inputPerMTok)},
    outputPerMTok: ${tsNum(r.outputPerMTok)},
    cacheReadPerMTok: ${tsNum(r.cacheReadPerMTok)},
    cacheWrite5mPerMTok: ${tsNum(w5)},
    cacheWrite1hPerMTok: ${tsNum(w1h)},
    status: ${tsString(r.status)},
    verified: ${tsString(r.verified)},
    effective: ${tsString(r.effective)},
    effectiveUntil: ${tsString(r.effectiveUntil)},
    contextTier: ${r.contextTier ? `{ op: ${tsString(r.contextTier.op)}, maxPromptTokens: ${r.contextTier.maxPromptTokens} }` : 'null'},
    source: ${tsString(r.source)},
    confidence: ${tsString(r.confidence)},
  }`;
  });

  const mults = snapshot.multipliers.filter(isSeedable).map(
    (m) => `  {
    platform: ${tsString(m.platform)},
    routingTier: ${tsString(m.routingTier)},
    multiplier: ${tsNum(m.multiplier)},
    appliesTo: ${tsString(m.appliesTo)},
    note: ${tsString(m.multiplierNote)},
    confidence: ${tsString(m.confidence)},
  }`
  );

  const excludedList = snapshot.prices
    .concat(snapshot.multipliers)
    .filter((r) => !isSeedable(r))
    .map((r) => ` *   - ${r.label || `${r.platform} / ${r.routingTier}`} (confidence: ${r.confidenceNote})`)
    .join('\n');

  const batch = snapshot.multipliers.find((m) => m.platform === 'any' && /batch/i.test(m.routingTier));

  return `${TS_HEADER(snapshot.snapshotDate, toIso(), { seeded: seedable.length, excluded })}
/* Rows deliberately NOT seeded, because an unowned number in code is worse than no number:
${excludedList || ' *   (none)'}
 */
${TS_TYPES}
/** The snapshot revision these prices came from. Stamp this on every ledger entry. */
export const PRICE_SHEET_REV = ${tsString(snapshot.snapshotDate)};

/** Days after which the sheet warns on import. Roughly one observed repricing cycle. */
export const STALENESS_WARN_DAYS = 45;

/** Flat asynchronous-batch multiplier. Stacks with cache reads. */
export const BATCH_MULTIPLIER = ${tsNum(batch ? batch.multiplier : 0.5)};

/**
 * Fallback when a served model is absent from the sheet. Using it is an ALERT, not a
 * rounding error: it means your cost model describes a system you do not have.
 *
 * Deliberately seeded with the MOST EXPENSIVE rates in the sheet. An unpriced model
 * should show up as a spike you investigate, not disappear into the noise as a cheap
 * default. A too-low default is how a model drift goes unnoticed for a billing cycle.
 */
export const DEFAULT_PRICE: Pick<PriceEntry, 'inputPerMTok' | 'outputPerMTok' | 'cacheReadPerMTok'> = {
  inputPerMTok: ${tsNum(Math.max(...seedable.map((r) => r.inputPerMTok || 0)) || 15)},
  outputPerMTok: ${tsNum(Math.max(...seedable.map((r) => r.outputPerMTok || 0)) || 75)},
  cacheReadPerMTok: null,
};

export const PRICES: PriceEntry[] = [
${entries.join(',\n')},
];

export const PLATFORM_MULTIPLIERS: PlatformMultiplier[] = [
${mults.join(',\n')},
];

/**
 * Load-time sanity assertions. These exist because a real upstream source shipped a
 * transposed input/output pair (a partner cloud's retail price API returned them
 * swapped, reproduced across two independent fetches). A naive seeder would have encoded
 * a several-fold input overcharge and nothing would have crashed. Cheap assertions catch
 * the class of bug whose symptom is a plausible wrong number.
 *
 * Exported so the detector itself is testable: an assertion nobody has ever seen fire is
 * indistinguishable from an assertion that cannot fire. See templates/pricing.test.ts.
 */
export function assertSheetSane(entries: PriceEntry[]): string[] {
  const problems: string[] = [];
  for (const e of entries) {
    if (e.outputPerMTok !== null && e.inputPerMTok !== null && e.outputPerMTok <= e.inputPerMTok) {
      problems.push(\`\${e.label}: output rate (\${e.outputPerMTok}) is not above input (\${e.inputPerMTok}) — likely transposed upstream\`);
    }
    if (e.cacheReadPerMTok !== null && e.inputPerMTok !== null && e.cacheReadPerMTok >= e.inputPerMTok) {
      problems.push(\`\${e.label}: cache read rate is not below the input rate\`);
    }
  }
  if (BATCH_MULTIPLIER > 1) problems.push('BATCH_MULTIPLIER is above 1 — a discount cannot cost more');
  return problems;
}

export const SHEET_PROBLEMS: string[] = assertSheetSane(PRICES);

/** Days since the sheet was cut. Callers warn past STALENESS_WARN_DAYS. */
export function priceSheetAgeDays(now: Date = new Date()): number {
  return Math.round((now.getTime() - Date.parse(PRICE_SHEET_REV + 'T00:00:00Z')) / 86400000);
}

function inWindow(e: PriceEntry, at: string): boolean {
  if (e.effective && at < e.effective) return false;
  if (e.effectiveUntil && at >= e.effectiveUntil) return false;
  return true;
}

function contextMatches(e: PriceEntry, promptTokens?: number): boolean {
  if (!e.contextTier) return true;
  if (promptTokens === undefined) return e.contextTier.op === '<=' || e.contextTier.op === '<';
  const t = e.contextTier.maxPromptTokens;
  switch (e.contextTier.op) {
    case '<=': return promptTokens <= t;
    case '<': return promptTokens < t;
    case '>=': return promptTokens >= t;
    case '>': return promptTokens > t;
  }
}

/**
 * Resolve a SERVED model id to a price row.
 *
 * Always pass the served model, never the requested one. Aliases resolve to dated
 * snapshots, partner-cloud ids carry region prefixes, deployment names hide the real
 * model, and a free tier can silently downgrade you to a cheaper model under load. If you
 * price the requested model you are pricing a system you did not run.
 */
export function priceFor(
  modelId: string,
  opts: { atDate?: string; promptTokens?: number } = {}
): { entry: PriceEntry | null; match: 'exact' | 'alias' | 'default' } {
  const at = opts.atDate ?? new Date().toISOString().slice(0, 10);
  const candidates = PRICES.filter((e) => inWindow(e, at) && contextMatches(e, opts.promptTokens));

  const exact = candidates.filter((e) => e.modelId === modelId);
  if (exact.length) return { entry: pickMostSpecific(exact), match: 'exact' };

  // Longest-match alias resolution, ONE DIRECTION ONLY: the queried id must CONTAIN a sheet
  // id. So a Bedrock 'global.anthropic.claude-opus-4-8-v1:0' resolves to 'claude-opus-4-8',
  // but a SHORTER undated alias ('claude-haiku-4-5' against the dated row
  // 'claude-haiku-4-5-20251001') does NOT resolve — it falls to the expensive default.
  //
  // That asymmetry is deliberate. Matching the other direction would let a query for
  // 'gemini-2.5-flash' also match 'gemini-2.5-flash-lite' and resolve to the CHEAPER row.
  // Under-pricing is the silent failure; over-pricing an unknown is the loud one, and loud
  // is what this sheet is built for. Pinned by templates/pricing.test.ts.
  let best: PriceEntry | null = null;
  for (const e of candidates) {
    if (modelId.startsWith(e.modelId) || modelId.includes(e.modelId)) {
      if (!best || e.modelId.length > best.modelId.length) best = e;
    }
  }
  if (best) return { entry: best, match: 'alias' };
  return { entry: null, match: 'default' };
}

function pickMostSpecific(entries: PriceEntry[]): PriceEntry {
  return entries.slice().sort((a, b) => (b.contextTier ? 1 : 0) - (a.contextTier ? 1 : 0))[0];
}

function multiplierFor(routing?: { platform: string; routingTier: string }): number {
  if (!routing) return 1;
  const m = PLATFORM_MULTIPLIERS.find(
    (x) => x.platform === routing.platform && x.routingTier.startsWith(routing.routingTier)
  );
  return m ? m.multiplier : 1;
}

/**
 * Pure cost arithmetic. No I/O, no clock of its own, fully unit-testable — which matters
 * because this is the one function whose silent wrongness would poison every number the
 * system reports.
 *
 * Two rules are embedded here and both are easy to get backwards:
 *   - Cache reads are billed SEPARATELY from input. Providers differ on whether their
 *     reported input count already excludes the cached portion; that normalisation is the
 *     ADAPTER's job, so by the time usage arrives here, inputTokens excludes cache reads.
 *   - Reasoning tokens are added to output ONLY when the provider reports them as a
 *     sibling rather than a subset. Adding a subset double-counts; skipping an addend
 *     undercounts by the whole thinking budget.
 */
export function computeCost(usage: UsageLike, opts: CostOptions & { modelId: string }): CostResult {
  const { entry, match } = priceFor(opts.modelId, { atDate: opts.atDate, promptTokens: opts.promptTokens });
  const rate = entry ?? { ...DEFAULT_PRICE, cacheWrite5mPerMTok: null, cacheWrite1hPerMTok: null };
  const mult = multiplierFor(opts.routing) * (opts.batch ? BATCH_MULTIPLIER : 1);

  const reasoning = usage.reasoningTokens ?? 0;
  const billableOutput = usage.reasoningInOutput ? usage.outputTokens : usage.outputTokens + reasoning;

  const perMTok = (tokens: number, r: number | null) => (r === null ? 0 : (tokens / 1_000_000) * r);

  const cost =
    perMTok(usage.inputTokens, rate.inputPerMTok) +
    perMTok(billableOutput, rate.outputPerMTok) +
    perMTok(usage.cacheReadTokens ?? 0, rate.cacheReadPerMTok ?? rate.inputPerMTok) +
    perMTok(usage.cacheWriteTokens ?? 0, (rate as PriceEntry).cacheWrite5mPerMTok ?? rate.inputPerMTok);

  return {
    costUsd: Math.round(cost * mult * 1e8) / 1e8,
    entry,
    match,
    estimated: match === 'default',
    priceSheetRev: PRICE_SHEET_REV,
    confidence: entry ? entry.confidence : 'low',
    multiplierApplied: mult,
  };
}
`;
}

/* ------------------------------------------------------------------ scaffolding */

function listTemplates(dir, base = dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, e.name);
    if (e.isDirectory()) listTemplates(full, base, out);
    else out.push(relative(base, full));
  }
  return out;
}

const CONTEXT_BEGIN = '<!-- BEGIN llm-finops project context (managed by init-finops.mjs) -->';
const CONTEXT_END = '<!-- END llm-finops project context -->';

function injectContext(targetFile, snippet, dryRun) {
  const block = `${CONTEXT_BEGIN}\n${snippet.trim()}\n${CONTEXT_END}\n`;
  let existing = '';
  if (existsSync(targetFile)) existing = readFileSync(targetFile, 'utf8');

  if (existing.includes(CONTEXT_BEGIN)) {
    const re = new RegExp(`${CONTEXT_BEGIN}[\\s\\S]*?${CONTEXT_END}\\n?`);
    const next = existing.replace(re, block);
    if (next === existing) return { action: 'unchanged', file: targetFile };
    if (!dryRun) writeFileSync(targetFile, next, 'utf8');
    return { action: 'updated', file: targetFile };
  }
  const next = existing ? `${existing.replace(/\s*$/, '')}\n\n${block}` : block;
  if (!dryRun) {
    mkdirSync(dirname(targetFile), { recursive: true });
    writeFileSync(targetFile, next, 'utf8');
  }
  return { action: existing ? 'appended' : 'created', file: targetFile };
}

function main() {
  const o = parseArgs(process.argv.slice(2));
  if (o.help) {
    process.stdout.write(HELP);
    return 0;
  }
  if (o.error) {
    process.stderr.write(`${o.error}\n\nRun with --help for usage.\n`);
    return 4;
  }

  let snapshot;
  try {
    snapshot = loadSnapshot();
  } catch (err) {
    process.stderr.write(`${err.message}\n`);
    return 4;
  }

  const log = [];
  const pricingTs = generatePricingTs(snapshot);

  // Always regenerate the skill's own templates/pricing.ts. It is a build artifact; an
  // out-of-date artifact beside a fresh snapshot is exactly the drift we are preventing.
  const skillPricing = join(TEMPLATES, 'pricing.ts');
  if (!o.dryRun) {
    mkdirSync(TEMPLATES, { recursive: true });
    writeFileSync(skillPricing, pricingTs, 'utf8');
  }
  log.push(`generated  ${relative(SKILL_ROOT, skillPricing)}  (from snapshot ${snapshot.snapshotDate}, ${snapshot.prices.filter(isSeedable).length} rows)`);

  if (!o.target) {
    log.push('');
    log.push('No --target given, so only the skill\'s own pricing.ts was regenerated.');
    log.push('Run with --target <repo> to scaffold a project. Next: node scripts/check-prices.mjs');
    process.stdout.write(log.join('\n') + '\n');
    return 0;
  }

  const target = resolve(o.target);
  if (!existsSync(target)) {
    process.stderr.write(`Target does not exist: ${target}\n`);
    return 4;
  }
  if (!existsSync(TEMPLATES)) {
    process.stderr.write(`No templates/ directory at ${TEMPLATES}. The skill install is incomplete.\n`);
    return 4;
  }

  const destRoot = join(target, o.dest);
  let written = 0;
  let skipped = 0;

  for (const rel of listTemplates(TEMPLATES)) {
    // VERIFY.md is documentation about the templates, not part of the runtime layer,
    // but it ships anyway: an UNVERIFIED adapter without its smoke test beside it is
    // how a wrong costUsd becomes a trusted number.
    const src = join(TEMPLATES, rel);
    const dest = join(destRoot, rel);
    const content = rel === 'pricing.ts' ? pricingTs : null;

    if (existsSync(dest) && !o.force) {
      // pricing.ts is generated, so overwriting it loses nothing a refresh cannot rebuild.
      if (rel === 'pricing.ts') {
        if (!o.dryRun) writeFileSync(dest, pricingTs, 'utf8');
        log.push(`regenerated ${join(o.dest, rel)}  (generated file — safe to overwrite)`);
        written++;
        continue;
      }
      const alt = `${dest}.new`;
      if (!o.dryRun) {
        mkdirSync(dirname(alt), { recursive: true });
        if (content !== null) writeFileSync(alt, content, 'utf8');
        else copyFileSync(src, alt);
      }
      log.push(`EXISTS     ${join(o.dest, rel)}  -> wrote ${join(o.dest, rel)}.new instead (diff and merge; not overwritten)`);
      skipped++;
      continue;
    }

    if (!o.dryRun) {
      mkdirSync(dirname(dest), { recursive: true });
      if (content !== null) writeFileSync(dest, content, 'utf8');
      else copyFileSync(src, dest);
    }
    log.push(`${existsSync(dest) && o.force ? 'overwrote ' : 'wrote     '} ${join(o.dest, rel)}`);
    written++;
  }

  if (o.context) {
    const snippetPath = join(TEMPLATES, 'project-context-snippet.md');
    if (existsSync(snippetPath)) {
      let ctxName = o.contextFile;
      if (!ctxName) {
        ctxName = existsSync(join(target, 'CLAUDE.md'))
          ? 'CLAUDE.md'
          : existsSync(join(target, 'AGENTS.md'))
            ? 'AGENTS.md'
            : 'CLAUDE.md';
      }
      const r = injectContext(join(target, ctxName), readFileSync(snippetPath, 'utf8'), o.dryRun);
      log.push(`context    ${r.action} ${ctxName} (block is marker-delimited, so re-running updates it in place)`);
    } else {
      log.push('context    SKIPPED — templates/project-context-snippet.md is missing');
    }
  }

  log.push('');
  log.push(`${o.dryRun ? 'DRY RUN — nothing written. ' : ''}${written} file(s) written, ${skipped} left untouched.`);
  if (skipped) {
    log.push(`The ${skipped} skipped file(s) already existed and were NOT overwritten; the new versions`);
    log.push(`are beside them as .new. Diff before merging — your edits are probably the ones you want.`);
  }
  log.push('');
  log.push('Next:');
  log.push('  1. node scripts/check-prices.mjs           (confirm no price leaked out of the snapshot)');
  log.push(`  2. read ${join(o.dest, 'VERIFY.md')}       (before trusting costUsd from an UNVERIFIED adapter)`);
  log.push('  3. choose a budget mode deliberately       (advisory never blocks — right for a demo, wrong for prod)');

  process.stdout.write(log.join('\n') + '\n');
  return written === 0 && skipped > 0 ? 1 : 0;
}

